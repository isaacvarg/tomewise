describe("tome vault rebuild: sessions Base", () => {
  it("writes sessions.base at the learning home root, listing session notes by subject and by week", async () => {
    const root = await morse();

    const result = await tome(["vault", "rebuild"], root);

    expect(result.code).toBe(0);
    expect(result.stdout).toBe("Wrote 5 vault files.");
    expect(await readFile(join(root, "sessions.base"), "utf8")).toBe(sessionsBase());
  });


  it("overwrites its own Base, edited or turned into CRLF with a BOM, but leaves a Base without the marker alone", async () => {
    const root = await morse();
    const base = join(root, "sessions.base");
    await writeFile(base, `\uFEFF${sessionsBase().replace("By week", "Weekly").replaceAll("\n", "\r\n")}`);

    await tome(["vault", "rebuild"], root);

    expect(await readFile(base, "utf8")).toBe(sessionsBase());

    const mine = sessionsBase().replace("# generatedBy: tomewise\n", "").replace("By week", "Weekly");
    await writeFile(base, mine);

    const result = await tome(["vault", "rebuild"], root);

    expect(result.code).toBe(0);
    expect(result.stdout).toBe(["Wrote 4 vault files.", "Left sessions.base alone: it has no generatedBy: tomewise marker."].join("\n"));
    expect(await readFile(base, "utf8")).toBe(mine);
  });
});
