import { mkdtemp, readdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { copyExample, snapshot, writeFiles } from "../../core/test/helpers.ts";
import { run } from "../src/main.ts";

async function morse(config: Record<string, unknown> = { vault: {} }): Promise<string> {
  const root = await copyExample("morse");
  const file = join(root, "tomewise.json");
  await writeFile(file, JSON.stringify({ ...JSON.parse(await readFile(file, "utf8")), ...config }));
  return root;
}

async function tome(args: string[], cwd: string) {
  const out: string[] = [];
  const err: string[] = [];
  const env = { HOME: await mkdtemp(join(tmpdir(), "tomewise-cli-home-")) };
  const code = await run(args, { cwd, env, stdout: (line) => out.push(line), stderr: (line) => err.push(line) });
  return { code, stdout: out.join("\n"), stderr: err.join("\n") };
}

const FIRST_LESSON = "sessions/morse-code/2026-10-30-01M6731E208N3RH6N28TSQZD7V.md";

describe("tome vault rebuild", () => {
  it("writes a note for a lesson session with its summary in frontmatter", async () => {
    const root = await morse();

    const result = await tome(["vault", "rebuild"], root);

    expect(result.stderr).toBe("");
    expect(result.code).toBe(0);
    expect(await readFile(join(root, FIRST_LESSON), "utf8")).toBe(
      [
        "---",
        "generatedBy: tomewise",
        'subject: "morse-code"',
        "date: 2026-10-30",
        'ref: "lesson:0001-k-and-m"',
        "durationMin: 0.3",
        "attempts: 6",
        "correct: 5",
        "wrong: 1",
        "skipped: 0",
        'lesson: "0001-k-and-m"',
        "---",
        "",
        "# Morse code: lesson 0001-k-and-m",
        "",
        "Lesson 0001-k-and-m on 2026-10-30, 0.3 min. 6 attempts: 5 correct, 1 wrong, 0 skipped (83%).",
        "",
        "Practised: letter-k, letter-m.",
        "",
        "Generated by Tomewise from history; edits are overwritten by `tome vault rebuild`.",
        "",
      ].join("\n"),
    );
  });

  it("writes one note per session, in a folder per subject", async () => {
    const root = await morse();

    await tome(["vault", "rebuild"], root);

    expect((await readdir(join(root, "sessions/morse-code"))).sort()).toEqual([
      "2026-10-30-01M6731E208N3RH6N28TSQZD7V.md",
      "2026-11-02-01M6ERD020P2CVN6ZRA7VR3Q9N.md",
      "2026-11-05-01M6NAP4308X87ZBZYKA7BNNWX.md",
      "2026-11-08-01M6YFY920Y53N456NMZNRR6JM.md",
    ]);
    const drill = await readFile(join(root, "sessions/morse-code/2026-11-05-01M6NAP4308X87ZBZYKA7BNNWX.md"), "utf8");
    expect(drill).toContain('ref: "drill:listen-kmrsu"\n');
    expect(drill).toContain("lesson: null\n");
    expect(drill).toContain("# Morse code: drill listen-kmrsu\n");
  });

  it("puts notes in the configured notes folder", async () => {
    const root = await morse({ vault: { notesFolder: "Learning/Sessions/" } });

    await tome(["vault", "rebuild"], root);

    expect(await readdir(join(root, "Learning/Sessions/morse-code"))).toHaveLength(4);
  });

  it("gives byte-identical notes when run again, and overwrites edits to generated notes", async () => {
    const root = await morse();
    await tome(["vault", "rebuild"], root);
    const first = await snapshot(join(root, "sessions"));
    await writeFile(join(root, FIRST_LESSON), (await readFile(join(root, FIRST_LESSON), "utf8")).replace("attempts: 6", "attempts: 60"));

    const result = await tome(["vault", "rebuild"], root);

    expect(result.code).toBe(0);
    expect(result.stdout).toBe("Wrote 5 vault files.");
    expect(await snapshot(join(root, "sessions"))).toEqual(first);
  });

  it("leaves learner files alone, even one named like a note but without the generated marker", async () => {
    const root = await morse();
    const mine = "# My notes on Morse\n\nK sounds like a kangaroo.\n";
    const lookalike = "---\nsubject: morse-code\n---\n\ngeneratedBy: tomewise is in my body, not my frontmatter\n";
    await writeFiles(root, { "sessions/morse-code/my-notes.md": mine, [FIRST_LESSON]: lookalike });

    const result = await tome(["vault", "rebuild"], root);

    expect(result.code).toBe(0);
    expect(result.stdout).toBe(
      ["Wrote 4 vault files.", `Left ${FIRST_LESSON} alone: it has no generatedBy: tomewise marker.`].join("\n"),
    );
    expect(await readFile(join(root, "sessions/morse-code/my-notes.md"), "utf8")).toBe(mine);
    expect(await readFile(join(root, FIRST_LESSON), "utf8")).toBe(lookalike);
  });

  it("still recognises its own notes after a checkout turns them into CRLF with a BOM", async () => {
    const root = await morse();
    await tome(["vault", "rebuild"], root);
    const note = await readFile(join(root, FIRST_LESSON), "utf8");
    await writeFile(join(root, FIRST_LESSON), `\uFEFF${note.replace("attempts: 6", "attempts: 60").replaceAll("\n", "\r\n")}`);

    const result = await tome(["vault", "rebuild"], root);

    expect(result.stdout).toBe("Wrote 5 vault files.");
    expect(await readFile(join(root, FIRST_LESSON), "utf8")).toBe(note);
  });

  it("refuses with a clear error when vault mode is off", async () => {
    for (const config of [{}, { vault: { enabled: false } }]) {
      const root = await morse(config);

      const result = await tome(["vault", "rebuild"], root);

      expect(result.code).toBe(2);
      expect(result.stdout).toBe("");
      expect(result.stderr).toBe(`Vault mode is off in ${join(root, "tomewise.json")}. Add "vault": {} to turn it on.`);
      expect(await readdir(root)).not.toContain("sessions");
    }
  });

  it("shows usage for anything but rebuild", async () => {
    const root = await morse();

    for (const args of [["vault"], ["vault", "build"], ["vault", "rebuild", "extra"]]) {
      const result = await tome(args, root);
      expect(result.code).toBe(2);
      expect(result.stderr).toContain("tome vault rebuild");
    }
  });
});

