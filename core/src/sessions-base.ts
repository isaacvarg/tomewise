import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { LearningHome } from "./load.ts";
import { GENERATED_MARKER, type GeneratedStatus, type WrittenNotes } from "./session-notes.ts";

export const SESSIONS_BASE_FILE = "sessions.base";

const DISPLAY_NAMES: Record<string, string> = {
  "file.name": "Session",
  "note.subject": "Subject",
  "note.date": "Date",
  "formula.week": "Week",
  "note.ref": "Ran",
  "note.durationMin": "Minutes",
  "note.attempts": "Attempts",
  "note.correct": "Correct",
  "note.wrong": "Wrong",
  "note.skipped": "Skipped",
  "note.lesson": "Lesson",
};

const SESSION_COLUMNS = ["note.ref", "note.durationMin", "note.attempts", "note.correct", "note.wrong", "note.skipped"];

function yamlQuoted(expression: string): string {
  return `'${expression.replaceAll("'", "''")}'`;
}

function view(name: string, groupBy: string, direction: "ASC" | "DESC", order: string[]): string[] {
  return [
    "  - type: table",
    `    name: ${name}`,
    "    groupBy:",
    `      property: ${groupBy}`,
    `      direction: ${direction}`,
    "    order:",
    ...order.map((column) => `      - ${column}`),
    "    sort:",
    "      - property: note.date",
    "        direction: DESC",
    "    summaries:",
    "      note.durationMin: Sum",
    "      note.attempts: Sum",
  ];
}

function sessionsBase(): string {
  return [
    `# ${GENERATED_MARKER}`,
    "# Generated by Tomewise; `tome vault rebuild` overwrites this file. Delete the line above to keep your own version.",
    "filters:",
    "  and:",
    `    - ${yamlQuoted('generatedBy == "tomewise"')}`,
    `    - ${yamlQuoted("!ref.isEmpty()")}`,
    "formulas:",
    `  week: ${yamlQuoted('note.date.format("GGGG-[W]WW")')}`,
    "properties:",
    ...Object.entries(DISPLAY_NAMES).flatMap(([column, displayName]) => [`  ${column}:`, `    displayName: ${displayName}`]),
    "views:",
    ...view("By subject", "note.subject", "ASC", ["file.name", "note.date", ...SESSION_COLUMNS, "note.lesson"]),
    ...view("By week", "formula.week", "DESC", ["file.name", "note.subject", "note.date", ...SESSION_COLUMNS]),
    "",
  ].join("\n");
}

export async function baseStatus(file: string): Promise<GeneratedStatus> {
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return "missing";
    throw error;
  }
  return text.replace(/^\uFEFF/, "").split(/\r?\n/, 1)[0]!.trimEnd() === `# ${GENERATED_MARKER}` ? "generated" : "learner";
}

export async function writeSessionsBase(home: LearningHome): Promise<WrittenNotes> {
  const file = join(home.root, SESSIONS_BASE_FILE);
  if ((await baseStatus(file)) === "learner") return { written: [], leftAlone: [SESSIONS_BASE_FILE] };
  await writeFile(file, sessionsBase());
  return { written: [SESSIONS_BASE_FILE], leftAlone: [] };
}
