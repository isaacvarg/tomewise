import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { isoDate, localDay, sessionMs } from "./activity.ts";
import { VaultDisabledError } from "./errors.ts";
import { readEvents } from "./event-store.ts";
import { parseRef, type LearningEvent, type Ref } from "./events.ts";
import { loadSubject, type LearningHome } from "./load.ts";
import { CONFIG_FILE } from "./find.ts";

export const GENERATED_MARKER = "generatedBy: tomewise";

export interface SessionSummary {
  subject: string;
  sessionId: string;
  date: string;
  ref: Ref;
  durationMin: number;
  attempts: number;
  correct: number;
  wrong: number;
  skipped: number;
  lesson: string | null;
  items: string[];
}

export interface SessionNote {
  path: string;
  summary: SessionSummary;
  content: string;
}

export interface WrittenNotes {
  written: string[];
  leftAlone: string[];
}

function summarise(subject: string, start: LearningEvent, events: readonly LearningEvent[], timezone: string): SessionSummary {
  const attempts = events.filter((event) => event.kind === "attempt");
  const count = (outcome: string) => attempts.filter((event) => event.outcome === outcome).length;
  const ref = parseRef(start.ref!)!;
  return {
    subject,
    sessionId: start.id,
    date: isoDate(localDay(Date.parse(start.ts), timezone)),
    ref,
    durationMin: Math.round(sessionMs(start, events) / 6_000) / 10,
    attempts: attempts.length,
    correct: count("correct"),
    wrong: count("wrong"),
    skipped: count("skipped"),
    lesson: ref.kind === "lesson" ? ref.id : null,
    items: [...new Set(attempts.flatMap((event) => parseRef(event.ref ?? "")?.id ?? []))].sort(),
  };
}

function render(summary: SessionSummary, subjectName: string): string {
  const { ref } = summary;
  const accuracy = summary.attempts === 0 ? "" : ` (${Math.round((summary.correct / summary.attempts) * 100)}%)`;
  const kindName = ref.kind[0]!.toUpperCase() + ref.kind.slice(1);
  return [
    "---",
    GENERATED_MARKER,
    `subject: ${JSON.stringify(summary.subject)}`,
    `date: ${summary.date}`,
    `ref: ${JSON.stringify(`${ref.kind}:${ref.id}`)}`,
    `durationMin: ${summary.durationMin}`,
    `attempts: ${summary.attempts}`,
    `correct: ${summary.correct}`,
    `wrong: ${summary.wrong}`,
    `skipped: ${summary.skipped}`,
    `lesson: ${JSON.stringify(summary.lesson)}`,
    "---",
    "",
    `# ${subjectName}: ${ref.kind} ${ref.id}`,
    "",
    `${kindName} ${ref.id} on ${summary.date}, ${summary.durationMin} min. ` +
      `${summary.attempts} ${summary.attempts === 1 ? "attempt" : "attempts"}: ${summary.correct} correct, ${summary.wrong} wrong, ${summary.skipped} skipped${accuracy}.`,
    "",
    ...(summary.items.length > 0 ? [`Practised: ${summary.items.join(", ")}.`, ""] : []),
    "Generated by Tomewise from history; edits are overwritten by `tome vault rebuild`.",
    "",
  ].join("\n");
}

function notesFolder(home: LearningHome): string {
  return home.config.vault.notesFolder.replace(/\/+$/, "");
}

export async function sessionNotes(home: LearningHome, subject: string): Promise<SessionNote[]> {
  const { name } = await loadSubject(home, subject);
  const events = await readEvents(home, subject);
  const bySession = Map.groupBy(events, (event) => event.sessionId);
  return events
    .filter((event) => event.kind === "session.start")
    .map((start) => {
      const summary = summarise(subject, start, bySession.get(start.id) ?? [], home.config.timezone);
      return {
        path: [notesFolder(home), subject, `${summary.date}-${summary.sessionId}.md`].join("/"),
        summary,
        content: render(summary, name),
      };
    });
}

type NoteStatus = "missing" | "generated" | "learner";

async function noteStatus(file: string): Promise<NoteStatus> {
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return "missing";
    throw error;
  }
  const lines = text.replace(/^\uFEFF/, "").split(/\r?\n/).map((line) => line.trimEnd());
  const close = lines.indexOf("---", 1);
  const frontmatter = lines[0] === "---" && close > 0 ? lines.slice(1, close) : [];
  return frontmatter.includes(GENERATED_MARKER) ? "generated" : "learner";
}

export async function writeSessionNotes(home: LearningHome, notes: readonly SessionNote[]): Promise<WrittenNotes> {
  const result: WrittenNotes = { written: [], leftAlone: [] };
  for (const note of notes) {
    const file = join(home.root, note.path);
    if ((await noteStatus(file)) === "learner") {
      result.leftAlone.push(note.path);
      continue;
    }
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, note.content);
    result.written.push(note.path);
  }
  return result;
}

export async function writeSessionNote(home: LearningHome, subject: string, sessionId: string): Promise<WrittenNotes> {
  assertVaultMode(home);
  const notes = await sessionNotes(home, subject);
  return writeSessionNotes(home, notes.filter((note) => note.summary.sessionId === sessionId));
}

function assertVaultMode(home: LearningHome): void {
  if (!home.config.vault.enabled) {
    throw new VaultDisabledError(
      `Vault mode is off in ${join(home.root, CONFIG_FILE)}. Add "vault": {} to turn it on.`,
    );
  }
}

export async function rebuildVault(home: LearningHome): Promise<WrittenNotes> {
  assertVaultMode(home);
  const notes: SessionNote[] = [];
  for (const subject of home.subjects) notes.push(...(await sessionNotes(home, subject)));
  return writeSessionNotes(home, notes);
}
