import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { appendEvents, loadLearningHome, rebuildVault, VaultDisabledError, writeCurriculumCopies } from "../src/index.ts";
import { copyExample, writeFiles } from "./helpers.ts";

async function morse(vault?: Record<string, unknown>): Promise<string> {
  const root = await copyExample("morse");
  const file = join(root, "tomewise.json");
  await writeFile(file, JSON.stringify({ ...JSON.parse(await readFile(file, "utf8")), vault }));
  return root;
}

const COPY = "subjects/morse-code/curriculum.md";

const read = (root: string) => readFile(join(root, COPY), "utf8");

function markDone(milestone: string, status: string, ts: string) {
  return { ts, subject: "morse-code", kind: "milestone.status", ref: `milestone:${milestone}`, schemaVersion: 2, data: { status } };
}

describe("curriculum copy", () => {
  it("is written by a rebuild beside curriculum.json, marked as generated, listing milestones in order", async () => {
    const root = await morse({});

    const result = await rebuildVault(await loadLearningHome(root));

    expect(result.curricula).toEqual({ written: [COPY], leftAlone: [] });
    expect(await read(root)).toBe(
      [
        "---",
        "generatedBy: tomewise",
        'subject: "morse-code"',
        "---",
        "",
        "# Morse code: curriculum",
        "",
        "## Koch letters",
        "",
        "1. Copy K, M, R, S and U: current",
        "   - Lessons: 0001-k-and-m, 0002-r, 0003-s, 0004-the-late-bump",
        "   - Exam: first-five",
        "2. Copy the next five letters: upcoming",
        "",
        "Generated by Tomewise from `curriculum.json` and history; edits are overwritten by `tome vault rebuild`.",
        "",
      ].join("\n"),
    );
  });

  it("shows the status the latest milestone.status event gives", async () => {
    const root = await morse({});
    const home = await loadLearningHome(root);
    await appendEvents(home, [
      markDone("next-five", "current", "2026-11-20T10:00:01.000Z"),
      markDone("first-five", "done", "2026-11-20T10:00:00.000Z"),
    ], { target: "main" });

    await writeCurriculumCopies(home, ["morse-code"]);

    const text = await read(root);
    expect(text).toContain("1. Copy K, M, R, S and U: done\n");
    expect(text).toContain("2. Copy the next five letters: current\n");
  });

  it("gives byte-identical output for the same inputs, overwriting edits to the copy", async () => {
    const root = await morse({});
    const home = await loadLearningHome(root);
    await rebuildVault(home);
    const first = await read(root);
    await writeFile(join(root, COPY), first.replace(": current", ": done"));

    await rebuildVault(home);

    expect(await read(root)).toBe(first);
  });

  it("leaves a learner's curriculum.md without the marker alone", async () => {
    const root = await morse({});
    const mine = "# My path\n\nK first, then M.\n";
    await writeFiles(root, { [COPY]: mine });
    const home = await loadLearningHome(root);

    expect((await rebuildVault(home)).curricula).toEqual({ written: [], leftAlone: [COPY] });
    expect(await writeCurriculumCopies(home, ["morse-code"])).toEqual({ written: [], leftAlone: [COPY] });
    expect(await read(root)).toBe(mine);
  });

  it("writes nothing for a subject without a curriculum", async () => {
    const root = await morse({});
    await writeFiles(root, { "subjects/flags/subject.json": { name: "Flags" } });
    const home = await loadLearningHome(root);

    expect(await writeCurriculumCopies(home, ["flags"])).toEqual({ written: [], leftAlone: [] });
    expect((await rebuildVault(home)).curricula).toEqual({ written: [COPY], leftAlone: [] });
    expect(await readdir(join(root, "subjects/flags"))).not.toContain("curriculum.md");
  });

  it("refuses with vault mode off", async () => {
    const root = await morse();

    await expect(writeCurriculumCopies(await loadLearningHome(root), ["morse-code"])).rejects.toThrow(VaultDisabledError);
    expect(await readdir(join(root, "subjects/morse-code"))).not.toContain("curriculum.md");
  });
});
